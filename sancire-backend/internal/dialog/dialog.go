// Package dialog implements the conversational layer of SancireAI: intent
// detection, the interactive fill-in wizard for the 7 modular documents,
// on-premise knowledge-base answers with citations, and chat-driven audits.
// It is fully deterministic (no external LLM required) and returns answers
// with rich metadata that the frontend renders as interactive cards.
package dialog

import (
	"context"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
	"time"

	"github.com/rs/zerolog/log"
	"sancireai/backend/internal/docx"
	"sancireai/backend/internal/kb"
	"sancireai/backend/internal/rag"
)

// File is an attachment forwarded from the chat client.
type File struct {
	Name string `json:"name"`
	Size int64  `json:"size"`
	Type string `json:"type"`
	Data string `json:"data,omitempty"` // base64 payload (used for .docx audits)
}

// Request is one inbound chat turn.
type Request struct {
	Ctx   context.Context
	Text  string
	Files []File
	Draft any
	Token func(string)
}

// ArtifactOut is a generated file that the handler must persist as an artifact.
type ArtifactOut struct {
	Data     []byte
	FileName string
	Title    string
	Kind     string
	Preview  string
}

// Outcome is the result of one chat turn.
type Outcome struct {
	Answer     string
	Meta       Meta
	NewDraft   any
	ChangeDraft bool
	ClearDraft bool
	Artifact   *ArtifactOut
}

// Meta mirrors the JSON metadata attached to assistant messages.
type Meta struct {
	Intent     string            `json:"intent,omitempty"`
	Sources    []Source          `json:"sources,omitempty"`
	Process    *Process          `json:"process,omitempty"`
	Document   *DocumentCard     `json:"document,omitempty"`
	Wizard     *WizardMeta       `json:"wizard,omitempty"`
	Audit      *docx.AuditReport `json:"audit,omitempty"`
	NotFound   bool              `json:"notFound,omitempty"`
	Clarifying bool              `json:"clarifying,omitempty"`
	FollowUps  []string          `json:"followUps,omitempty"`
}

// Source points at a normative document section.
type Source struct {
	ID            string `json:"id"`
	DocumentTitle string `json:"documentTitle"`
	Clause        string `json:"clause"`
	Excerpt       string `json:"excerpt"`
	UpdatedAt     string `json:"updatedAt"`
}

// Process is a rendered step-by-step diagram.
type Process struct {
	Title string        `json:"title"`
	Steps []ProcessStep `json:"steps"`
}

// ProcessStep is one diagram step.
type ProcessStep struct {
	ID          string `json:"id"`
	Title       string `json:"title"`
	Description string `json:"description"`
	Deadline    string `json:"deadline,omitempty"`
	Department  string `json:"department,omitempty"`
}

// DocumentCard describes a generated document ready for download.
type DocumentCard struct {
	Title      string `json:"title"`
	Kind       string `json:"kind"`
	FileName   string `json:"fileName"`
	Preview    string `json:"preview"`
	ArtifactID string `json:"artifactId,omitempty"`
	ModuleID   string `json:"moduleId,omitempty"`
}

// Engine answers chat turns. Deterministic by default; when the local LLM
// (Ollama) and/or Qdrant are available, normative answers are generated by
// the model with strict grounding and validated citations.
type Engine struct {
	ix           *kb.Index
	templatesDir string
	llm          *rag.Engine
}

// UseLLM wires the RAG engine used for AI-grounded answers and vector search.
func (e *Engine) UseLLM(r *rag.Engine) { e.llm = r }

// ReloadRegulations swaps the admin-uploaded regulation chunks in the index.
func (e *Engine) ReloadRegulations(chunks []*kb.Chunk) {
	if e.ix != nil {
		e.ix.SetRegulations(chunks)
		log.Info().Int("chunks", len(chunks)).Msg("kb regulations reloaded")
	}
}

// NewEngine loads the local knowledge index.
func NewEngine(templatesDir, corpusDir string) *Engine {
	ix, err := kb.Load(corpusDir)
	if err != nil {
		log.Warn().Err(err).Msg("kb index not loaded, chat will rely on canned intents only")
	}
	return &Engine{ix: ix, templatesDir: templatesDir}
}

var (
	reModuleCode   = regexp.MustCompile(`(?i)[МM][- ]?0([1-7])`)
	reHardQuestion = regexp.MustCompile(`^(как|кто|что|где|когда|почему|зачем|сколько|какие|какой|какая|каковы|каким образом|есть ли|можно ли|нужно ли|обязан|в какой|кто вправе|срок|порядок|требован)`)
	reCreateVerb   = regexp.MustCompile(`(?i)(созда\w*|сформируй\w*|сдела\w*|оформи\w*|заполни\w*|собери\w*|выпусти\w*|подготов\w*|выда\w*|нужен|нужна|нужно|хочу)`)
	reCreateNoun   = regexp.MustCompile(`(?i)(приказ\w*|распоряжен\w*|документ\w*|служебн\w* записк\w*|письм\w*|заявлен\w*|регламент\w*|акт\b|командиров\w*|отчет\w*|отчёт\w*|представлен\w*)`)
	reCreateHow    = regexp.MustCompile(`(?i)(как создать|как оформить|как сформировать|как сделать|как заполнить|как подготовить|как получить)`)
	reAuditVerb    = regexp.MustCompile(`(?i)(провер\w*|аудир\w*|найди ошибки|найти ошибки|просмотри проект|проанализируй)`)
	reAuditNoun    = regexp.MustCompile(`(?i)(документ|файл|проект|готовый|\.docx|модульн\w*)`)
	reFeedback     = regexp.MustCompile(`(?i)(предложени\w*|баг|дефект|улучшени\w*|не работает|не отвечает|жалоб\w*|проблема с чатом|ошибк\w* в боте)`)
	reCancel       = regexp.MustCompile(`^(отмена|отмени\w*|стоп|перестань|выход|сброс|начать заново|прекрати)$`)
	reSkip         = regexp.MustCompile(`^(пропусти\w*|пропуск|skip|дальше)$`)
	reSummaryAsk   = regexp.MustCompile(`^(список|покажи значения|что собрано|что уже|текущие значения|сводка)$`)
	reFinalize     = regexp.MustCompile(`(?i)^(сформируй|создать документ|сформировать документ|готово|подтверждаю|давай|да|ок|вперёд|вперед|согласен)$`)
	reEdit         = regexp.MustCompile(`(?i)^(изменить|править|скорректировать|редактировать|вернуться)$`)
	reDateQ        = regexp.MustCompile(`(?i)((какой|какая|какое|назови|скажи|поставь)\s+(сегодня|седня|текущи\w*|нынешни\w*|сегодняшни\w*)?\s*(день|дата|число)|дата\s+(сегодня|седня|сегодняшн\w+)|(сегодня|седня)\s+(какой|какая|какое)\s+(день|дата|число)|что\s+сегодня\s+за\s+день|сегодняшн\w+\s+дат|какое\s+сегодня\s+число)`)
	reTimeQ        = regexp.MustCompile(`(?i)(которы[йя]\s+час|сколько\s+времени|текуще[ея]\s+время|сколько\s+часов\s+сейчас)`)
)

var (
	ruMonths   = [...]string{"января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"}
	ruWeekdays = [...]string{"понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"}
)

// answerDateOrTime handles deterministic calendar/clock questions so they
// never reach the knowledge base (where they used to match random clauses).
func answerDateOrTime(e *Engine, req Request, norm string) (Outcome, bool) {
	if reDateQ.MatchString(norm) {
		now := time.Now()
		answer := fmt.Sprintf("Сегодня %d %s %d г., %s.",
			now.Day(), ruMonths[int(now.Month())-1], now.Year(), ruWeekdays[(int(now.Weekday())+6)%7])
		return e.reply(req, answer, Meta{Intent: "date", FollowUps: []string{
			"Что ты умеешь?", "Порядок согласования внутреннего документа", "Приказ о вводе ИС в эксплуатацию (М-01)",
		}}), true
	}
	if reTimeQ.MatchString(norm) {
		now := time.Now()
		answer := fmt.Sprintf("Сейчас %02d:%02d (местное время сервера).", now.Hour(), now.Minute())
		return e.reply(req, answer, Meta{Intent: "time", FollowUps: []string{
			"Какой сегодня день?", "Что ты умеешь?", "Задать вопрос эксперту",
		}}), true
	}
	return Outcome{}, false
}

// Section exposes a knowledge chunk for the regulations reader endpoint.
func (e *Engine) Section(id string) (kb.Chunk, bool) {
	if e.ix == nil {
		return kb.Chunk{}, false
	}
	c, ok := e.ix.Get(id)
	if !ok || c == nil {
		return kb.Chunk{}, false
	}
	return *c, true
}

// CorpusSize reports how many knowledge chunks are currently indexed. It backs
// the admin statistics endpoint and the help text.
func (e *Engine) CorpusSize() int {
	if e.ix == nil {
		return 0
	}
	return e.ix.Len()
}

// Respond processes one chat turn.
func (e *Engine) Respond(req Request) Outcome {
	text := strings.TrimSpace(req.Text)
	norm := normalizeText(text)

	// 1. Audit whenever a .docx payload arrives.
	if out, ok := e.tryAuditFiles(req, norm); ok {
		return out
	}

	// 2. Active wizard consumes ordinary answers.
	if draft := loadState(req.Draft); draft != nil {
		if out, ok := e.wizardTurn(req, draft, text, norm); ok {
			return out
		}
		// fall through: the turn is a brand-new command (handled below)
	}

	// 3. Intents.
	if isGreeting(norm) {
		return e.reply(req, greetingText, Meta{
			Intent:    "greeting",
			FollowUps: []string{"Что ты умеешь?", "Согласование внутреннего документа", "Приказ о вводе ИС в эксплуатацию (М-01)"},
		})
	}
	if out, ok := answerDateOrTime(e, req, norm); ok {
		return out
	}
	if isSmallTalk(norm) {
		return e.reply(req, smallTalkText, Meta{
			Intent:    "smallTalk",
			FollowUps: []string{"Порядок согласования приказа", "Сформировать документ по модулю", "Проверить готовый документ"},
		})
	}
	if reFeedback.MatchString(norm) {
		return e.reply(req, feedbackText, Meta{
			Intent:    "feedback",
			NotFound:  true,
			FollowUps: []string{"Проверить готовый документ", "Задать вопрос эксперту"},
		})
	}

	// 4. Explicit module code or an explicit "create …" request starts the wizard.
	if modID, ok := detectModule(text, norm); ok {
		return e.startWizard(req, modID)
	}
	if isHelp(norm) {
		return e.reply(req, helpText(e), Meta{
			Intent:    "help",
			FollowUps: helpFollowUps(),
		})
	}
	hardQuestion := reHardQuestion.MatchString(norm) || strings.Contains(text, "?") || strings.Contains(text, "？")
	if reCreateVerb.MatchString(norm) && reCreateNoun.MatchString(norm) && !hardQuestion {
		return e.startClarify(req)
	}
	if reCreateVerb.MatchString(norm) && reCreateHow.MatchString(norm) {
		// "как создать приказ о вводе ИС" → straight into the wizard when the
		// request maps to a known module; otherwise fall through to the KB.
		if modID, ok := detectModule(text, norm); ok {
			return e.startWizard(req, modID)
		}
	}

	// 5. Audit-without-file instructions.
	if reAuditVerb.MatchString(norm) && (reAuditNoun.MatchString(norm) || strings.HasSuffix(norm, "docx")) {
		return e.reply(req, auditInviteText, Meta{
			Intent:    "audit.invite",
			FollowUps: []string{"Сформировать документ по модулю", "Порядок согласования проекта документа"},
		})
	}

	// 6. Knowledge-base answer (covers questions, processes and refusals).
	return e.compose(req, text, norm)
}

// reply emits a canned answer (optionally streamed via SSE).
func (e *Engine) reply(req Request, answer string, meta Meta) Outcome {
	emit(req.Token, answer)
	return Outcome{Answer: answer, Meta: meta}
}

// emit streams an answer through the SSE callback in small chunks so the
// frontend can render it progressively. It is a no-op without a callback.
func emit(token func(string), text string) {
	if token == nil || text == "" {
		return
	}
	runes := []rune(text)
	const chunkSize = 24
	for s := 0; s < len(runes); s += chunkSize {
		end := s + chunkSize
		if end > len(runes) {
			end = len(runes)
		}
		token(string(runes[s:end]))
		if end < len(runes) {
			time.Sleep(8 * time.Millisecond)
		}
	}
}

// ---------------------------------------------------------------------------
// Audits from chat attachments
// ---------------------------------------------------------------------------

func (e *Engine) tryAuditFiles(req Request, norm string) (Outcome, bool) {
	for _, f := range req.Files {
		if !strings.HasSuffix(strings.ToLower(f.Name), ".docx") || f.Data == "" {
			continue
		}
		data, err := base64.StdEncoding.DecodeString(f.Data)
		if err != nil {
			return e.reply(req, "Не удалось прочитать файл — повреждённая кодировка. Попробуйте загрузить документ заново.", Meta{Intent: "audit.error"}), true
		}
		report, err := docx.AuditDocx(data, f.Name, "")
		if err != nil {
			return e.reply(req, fmt.Sprintf("Не удалось разобрать файл `%s`: %s\n\nПроверьте, что это корректный .docx.", f.Name, err.Error()), Meta{Intent: "audit.error", NotFound: true}), true
		}
		answer := auditAnswer(report)
		return e.reply(req, answer, Meta{
			Intent:    "audit.report",
			Audit:     report,
			FollowUps: auditFollowUps(report),
		}), true
	}
	return Outcome{}, false
}

