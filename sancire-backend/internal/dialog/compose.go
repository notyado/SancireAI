var reCite = regexp.MustCompile(`\{\{s:([^}]+)\}\}`)

func chunkFromScored(v rag.ScoredChunk) *kb.Chunk {
	return &kb.Chunk{
		ID:            v.SectionID,
		DocumentTitle: v.DocumentTitle,
		Clause:        v.Clause,
		Title:         v.Title,
		Text:          v.Text,
		Page:          v.Page,
		UpdatedAt:     v.UpdatedAt,
		VersionID:     v.VersionID,
		Category:      v.Category,
	}
}

func toScoredChunks(hits []kb.Scored) []rag.ScoredChunk {
	out := make([]rag.ScoredChunk, 0, len(hits))
	for _, h := range hits {
		out = append(out, rag.ScoredChunk{
			ChunkID:       h.Chunk.ID,
			SectionID:     h.Chunk.ID,
			DocumentTitle: h.Chunk.DocumentTitle,
			Clause:        h.Chunk.Clause,
			Title:         h.Chunk.Title,
			Text:          h.Chunk.Text,
			Page:          h.Chunk.Page,
			UpdatedAt:     h.Chunk.UpdatedAt,
			VersionID:     h.Chunk.VersionID,
			Category:      h.Chunk.Category,
			Score:         h.Score,
		})
	}
	return out
}

// aiMeta collects sources for every cited fragment of an AI answer.
func aiMeta(ans string, candidates []kb.Scored, norm string) Meta {
	byID := map[string]*kb.Chunk{}
	for i := range candidates {
		byID[candidates[i].Chunk.ID] = candidates[i].Chunk
	}
	var sources []Source
	seen := map[string]bool{}
	for _, m := range reCite.FindAllStringSubmatch(ans, -1) {
		if len(m) < 2 || seen[m[1]] {
			continue
		}
		if c, ok := byID[m[1]]; ok {
			seen[m[1]] = true
			sources = append(sources, sourceOf(c))
		}
	}
	top := candidates[0].Chunk
	meta := Meta{
		Intent:    "answer.ai",
		Sources:   sources,
		FollowUps: followUpsFor(top, reProcessQ.MatchString(norm)),
	}
	return meta
}

const (
	refusalText = "В предоставленных материалах нет однозначного ответа на этот вопрос.\n\n" +
		"Чтобы не выдавать домыслы за нормативные требования, я отвечу только по текстам, которые есть в базе. " +
		"Попробуйте переформулировать вопрос (с указанием вида документа или ситуации) или задайте его эксперту ДОУ."

	indexMissingText = "База знаний не подключена — отвечать со ссылками на пункты пока невозможно. " +
		"Уточните настройки подключения или задайте вопрос эксперту ДОУ."
)

func sourceOf(c *kb.Chunk) Source {
	return Source{
		ID:            c.ID,
		DocumentTitle: c.DocumentTitle,
		Clause:        c.Clause,
		Excerpt:       c.Excerpt(400),
		UpdatedAt:     c.UpdatedAt,
	}
}

// bestSentence extracts the span of the chunk that overlaps the query most.
// For table-like texts (the visa matrix) sentence splitting is useless, so we
// slide a window and keep the one containing the most distinct query terms.
func bestSentence(c *kb.Chunk, query string) string {
	text := strings.TrimSpace(c.Text)
	if text == "" {
		return ""
	}
	runes := []rune(text)
	if len(runes) <= maxSentenceRunes {
		return text
	}

	// Distinct, meaningful query terms (stopwords are already filtered out by
	// the index tokeniser, so scoring is not diluted by «можно», «какой», …).
	var terms []string
	seen := map[string]bool{}
	for _, t := range kb.Tokenize(query) {
		if len([]rune(t)) < minQueryTermRunes || seen[t] {
			continue
		}
		seen[t] = true
		terms = append(terms, t)
	}
	if len(terms) == 0 {
		return c.Excerpt(maxSentenceRunes)
	}

	// Slide a rune window over the lower-cased text and keep the window with
	// the most distinct query terms.
	lowerRunes := []rune(strings.ToLower(strings.ReplaceAll(text, "ё", "е")))
	bestStart, bestScore := 0, -1
	for start := 0; start < len(lowerRunes); start += sentenceStep {
		end := min(start+sentenceWindow, len(lowerRunes))
		piece := string(lowerRunes[start:end])
		score := 0
		for _, t := range terms {
			if strings.Contains(piece, t) {
				score++
			}
		}
		if score > bestScore {
			bestScore = score
			bestStart = start
		}
		if end == len(lowerRunes) {
			break
		}
	}
	if bestScore <= 0 {
		return c.Excerpt(maxSentenceRunes)
	}
	// Align to word boundaries.
	lo := bestStart
	for lo > 0 && runes[lo] != ' ' && runes[lo] != '\n' {
		lo--
	}
	hi := min(lo+sentenceWindow, len(runes))
	for hi < len(runes) && runes[hi] != ' ' && runes[hi] != '\n' {
		hi++
	}
	span := strings.TrimSpace(string(runes[lo:hi]))
	if span == "" {
		return c.Excerpt(maxSentenceRunes)
	}
	return truncateRunes(span, hardSentenceCut) + suffixIfTruncated(span, hardSentenceCut)
}

func splitSentences(s string) []string {
	var parts []string
	var cur []rune
	runes := []rune(s)
	for i, r := range runes {
		cur = append(cur, r)
		if r == '.' || r == '!' || r == '?' {
			// sentence ends at punctuation followed by whitespace / end
			if i+1 >= len(runes) || runes[i+1] == ' ' || runes[i+1] == '\n' {
				parts = append(parts, string(cur))
				cur = cur[:0]
			}
		}
	}
	if len(cur) > 0 {
		parts = append(parts, string(cur))
	}
	var out []string
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if len(p) >= 30 {
			out = append(out, p)
		}
	}
	return out
}

func firstSentence(s string) string {
	if parts := splitSentences(s); len(parts) > 0 {
		return truncateRunes(parts[0], firstSentenceRunes) + suffixIfTruncated(parts[0], firstSentenceRunes)
	}
	c := &kb.Chunk{Text: s}
	return c.Excerpt(firstSentenceRunes)
}

// truncateRunes cuts s to at most n runes without splitting a character.
func truncateRunes(s string, n int) string {
	runes := []rune(s)
	if len(runes) <= n {
		return s
	}
	return string(runes[:n])
}

// suffixIfTruncated is the ellipsis that marks a truncated fragment.
func suffixIfTruncated(s string, n int) string {
	if len([]rune(s)) > n {
		return "…"
	}
	return ""
}

func followUpsFor(top *kb.Chunk, isProcess bool) []string {
	base := []string{"Показать пошагово", "Сформировать документ по модулю", "Проверить готовый документ", "Задать вопрос эксперту"}
	if top != nil && top.Category == "visa_matrix" {
		base = []string{"Какой маршрут визирования для приказа?", "Кто визирует проект документа?", "Сформировать документ по модулю", "Задать вопрос эксперту"}
	}
	if isProcess {
		base = []string{"Сформировать документ по модулю", "Какие сроки согласования?", "Проверить готовый документ", "Задать вопрос эксперту"}
	}
	return base
}

