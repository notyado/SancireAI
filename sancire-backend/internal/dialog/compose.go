// Retrieval thresholds of the composer. Lexical scores are unbounded term
// weights, vector scores are cosine similarities in [0;1].
const (
	searchLimit      = 5    // chunks pulled from the local index
	vectorLimit      = 4    // chunks pulled from Qdrant
	confident        = 6.0  // lexical score that alone justifies an answer
	weak             = 3.0  // below this the lexical evidence is only "related"
	vecRescue        = 0.62 // cosine score that may rescue a weak lexical match
	maxContextChunks = 5    // fragments forwarded to the model in one prompt
)

// Window parameters of bestSentence / firstSentence (runes).
const (
	sentenceWindow     = 430 // runes in one scoring window
	sentenceStep       = 60  // step the window slides by
	maxSentenceRunes   = 460 // a chunk shorter than this is quoted whole
	hardSentenceCut    = 470 // absolute cap of the quoted span
	firstSentenceRunes = 240 // cap of a step description in a process card
	minQueryTermRunes  = 4   // shorter terms carry no topical signal
)

var (
	reProcessQ = regexp.MustCompile(`(порядок|последователь|этап|шаг|как\s|что дальше|далее|маршрут|организац\w+\s+согласован|организовать\s+согласован)`)
	reNegative = regexp.MustCompile(`(не регламентир|не установлено|не предусмотрен|не указана|не указывается|не содержит|не требует|не производится|не допускается|отсутствует)`)
)

// compose builds a knowledge answer. With the local LLM available and a
// confident retrieval (lexical or vector), the answer is generated by the
// model strictly from the retrieved fragments and validated for citations;
// otherwise the deterministic composer answers directly from the texts.
func (e *Engine) compose(req Request, text, norm string) Outcome {
	ctx := req.Ctx
	if ctx == nil {
		ctx = context.Background()
	}

	if e.ix == nil || e.ix.Len() == 0 {
		return e.reply(req, indexMissingText, Meta{Intent: "answer.notFound", NotFound: true,
			FollowUps: []string{"Что ты умеешь?", "Приказ о вводе ИС в эксплуатацию (М-01)", "Задать вопрос эксперту"}})
	}
	hits := e.ix.Search(text, searchLimit)
	lexTop := 0.0
	if len(hits) > 0 {
		lexTop = hits[0].Score
	}

	// Vector fusion — only when Qdrant is up; harmless when it is not.
	// A vector hit may SUPPLEMENT lexical evidence or rescue a query only
	// when it is very confident on its own: casual/noise queries whose
	// embeddings land near arbitrary chunks must not bypass the refusal.
	var vec []rag.ScoredChunk
	if e.llm != nil {
		if v, err := e.llm.VectorSearchText(ctx, text, vectorLimit); err == nil {
			vec = v
		}
	}
	vecConfident := false
	if len(vec) > 0 {
		vecConfident = lexTop >= weak || vec[0].Score >= vecRescue
	}

	// Merge vector candidates lexical search may have missed / promote them
	// when lexical confidence is weak.
	if vecConfident {
		inHits := map[string]bool{}
		for _, h := range hits {
			inHits[h.Chunk.ID] = true
		}
		var extra []kb.Scored
		for _, v := range vec {
			if v.SectionID == "" || inHits[v.SectionID] {
				continue
			}
			extra = append(extra, kb.Scored{Chunk: chunkFromScored(v), Score: confident + 1})
		}
		if lexTop < confident {
			hits = append(extra, hits...)
		} else {
			hits = append(hits, extra...)
		}
	}

	// 1. Intelligent AI answer — streams live when LLM is available.
	if e.llm != nil && e.llm.LLMHealthy(ctx) {
		candidates := hits
		if len(candidates) > maxContextChunks {
			candidates = candidates[:maxContextChunks]
		}
		ans, _, err := e.llm.GroundedAnswerStream(ctx, text, toScoredChunks(candidates), req.History, func(s string) {
			emit(req.Token, s)
		})
		if err == nil && len(strings.TrimSpace(ans)) > 0 {
			meta := aiMeta(ans, candidates, norm)
			if len(meta.Sources) == 0 {
				meta.Intent = "conversational"
				meta.FollowUps = []string{"Порядок согласования приказа", "Сформировать приказ по модулю", "Проверить готовый документ .docx"}
			}
			return Outcome{Answer: ans, Meta: meta}
		}
		if err != nil {
			log.Warn().Err(err).Msg("llm answer stream failed, falling back to deterministic compose")
		}
	}

	// 2. Deterministic Fallbacks (offline or when LLM fails)
	if lexTop < weak && !vecConfident {
		return e.reply(req, refusalText, Meta{
			Intent:    "answer.notFound",
			NotFound:  true,
			FollowUps: []string{"Порядок согласования внутреннего документа", "Проверить готовый документ", "Задать вопрос эксперту"},
		})
	}
	if lexTop < confident && !vecConfident {
		var b strings.Builder
		b.WriteString("Однозначного ответа на этот вопрос в предоставленных материалах я не нашёл — не хочу выдумывать.\n\nБлижайшие по смыслу разделы (возможно, релевантны):\n")
		var sources []Source
		for i, h := range hits {
			if i >= 3 {
				break
			}
			b.WriteString(fmt.Sprintf("- %s документа «%s»: {{s:%s}}%s{{/s}}\n", h.Chunk.Clause, h.Chunk.DocumentTitle, h.Chunk.ID, h.Chunk.Excerpt(220)))
			sources = append(sources, sourceOf(h.Chunk))
		}
		b.WriteString("\nЕсли вопрос не про эти разделы — уточните формулировку или задайте его эксперту ДОУ.")
		return e.reply(req, b.String(), Meta{
			Intent:    "answer.related",
			Sources:   sources,
			NotFound:  true,
			FollowUps: []string{"Задать вопрос эксперту", "Порядок согласования внутреннего документа", "Что ты умеешь?"},
		})
	}

	top := hits[0].Chunk
	sentence := bestSentence(top, text)
	primaryNegative := reNegative.MatchString(sentence)

	var b strings.Builder
	if primaryNegative {
		b.WriteString("**Важно:** материалы прямо указывают, что этот вопрос **не регламентирован** (или регламентирован с оговоркой) — структуру и порядок «по умолчанию» не рекомендую придумывать.\n\n")
	}
	isProcess := reProcessQ.MatchString(norm)

	sources := []Source{sourceOf(top)}
	used := map[string]bool{top.ID: true}

	b.WriteString(fmt.Sprintf("Ответ по материалам — %s документа «%s»:\n\n", top.Clause, top.DocumentTitle))
	b.WriteString(fmt.Sprintf("{{s:%s}}%s{{/s}}\n", top.ID, sentence))

	if isProcess {
		b.WriteString("\n**Порядок (по пунктам материалов):**\n")
		steps := []ProcessStep{}
		n := 0
		for _, h := range hits {
			if used[h.Chunk.ID] {
				continue
			}
			n++
			stepSentence := firstSentence(h.Chunk.Text)
			b.WriteString(fmt.Sprintf("%d. %s — {{s:%s}}%s{{/s}}\n", n, h.Chunk.Clause, h.Chunk.ID, stepSentence))
			steps = append(steps, ProcessStep{
				ID:          fmt.Sprintf("step-%d", n),
				Title:       h.Chunk.Clause,
				Description: stepSentence,
			})
			sources = append(sources, sourceOf(h.Chunk))
			used[h.Chunk.ID] = true
			if n >= 3 {
				break
			}
		}
		if len(steps) > 0 {
			meta := Meta{
				Intent:  "answer.process",
				Sources: sources,
				Process: &Process{Title: "Опорные пункты по вопросу", Steps: steps},
			}
			meta.FollowUps = followUpsFor(top, true)
			return e.reply(req, b.String(), meta)
		}
	} else if len(hits) > 1 {
		h := hits[1]
		b.WriteString(fmt.Sprintf("\nДополнительно — %s («%s»): {{s:%s}}%s{{/s}}\n", h.Chunk.Clause, h.Chunk.DocumentTitle, h.Chunk.ID, h.Chunk.Excerpt(260)))
		sources = append(sources, sourceOf(h.Chunk))
	}
	b.WriteString("\nСсылка на источник — карточка ниже. Если нужен порядок целиком (пошагово) — скажите «Показать пошагово».")

	meta := Meta{Intent: "answer", Sources: sources}
	meta.FollowUps = followUpsFor(top, isProcess)
	return e.reply(req, b.String(), meta)
}

