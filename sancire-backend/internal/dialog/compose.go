func auditAnswer(r *docx.AuditReport) string {
	var b strings.Builder
	switch r.Status {
	case docx.TrafficLightGreen:
		b.WriteString("**Проверка завершена — зелёный статус.**\n")
	case docx.TrafficLightYellow:
		b.WriteString("**Проверка завершена — есть предупреждения.**\n")
	default:
		b.WriteString("**Проверка завершена — критические замечания.**\n")
	}
	b.WriteString(r.StatusSummary + "\n")

	if len(r.VisaRouting.RequiredVisas) > 0 {
		b.WriteString("\n**Маршрут визирования по Матрице:**\n")
		for _, v := range r.VisaRouting.RequiredVisas {
			if !v.Required {
				continue
			}
			b.WriteString("- " + v.Department)
			if v.Reason != "" {
				b.WriteString(" — " + strings.ToLower(v.Reason))
			}
			b.WriteString("\n")
		}
		if len(r.VisaRouting.AppliedRules) > 0 {
			b.WriteString("\n**Обоснование расчёта:**\n")
			for _, rule := range r.VisaRouting.AppliedRules {
				b.WriteString("- " + rule + "\n")
			}
		}
	}

	if len(r.Findings) > 0 {
		b.WriteString("\n**Замечания:**\n")
		for i, f := range r.Findings {
			if i >= 8 {
				b.WriteString(fmt.Sprintf("… и ещё %d — в подробном отчёте ниже.\n", len(r.Findings)-8))
				break
			}
			sev := "INFO"
			switch f.Severity {
			case docx.SeverityCritical:
				sev = "КРИТ"
			case docx.SeverityWarning:
				sev = "ПРЕДУПР"
			}
			b.WriteString(fmt.Sprintf("- [%s] %s", sev, f.Title))
			if f.Location != "" {
				b.WriteString(" (" + f.Location + ")")
			}
			b.WriteString("\n")
		}
	} else {
		b.WriteString("\nЗамечаний не найдено.")
	}
	b.WriteString("\n\nПолный отчёт — в карточке ниже.")
	return b.String()
}

func auditFollowUps(r *docx.AuditReport) []string {
	if r == nil {
		return []string{"Порядок согласования проекта документа", "Задать вопрос эксперту"}
	}
	if r.Status == docx.TrafficLightRed {
		return []string{"Как устранить замечания?", "Какой будет маршрут визирования?", "Порядок согласования проекта документа"}
	}
	return []string{"Какой будет маршрут визирования?", "Сформировать документ по модулю", "Задать вопрос эксперту"}
}
