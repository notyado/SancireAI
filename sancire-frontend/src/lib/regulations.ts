export const allSections = regulations.flatMap((regulation) =>
  regulation.sections.map((section) => ({
    ...section,
    regulationId: regulation.id,
    regulationTitle: regulation.title,
    shortTitle: regulation.shortTitle,
    updatedAt: regulation.updatedAt,
  })),
);
export function findSection(id: string) {
  return allSections.find((section) => section.id === id);
}
export function findRegulation(id: string) {
  return regulations.find((item) => item.id === id);
}
export function formatUpdatedAt(value: string) {
  const [year, month, day] = value.split("-");
  return `${day}.${month}.${year}`;
}
